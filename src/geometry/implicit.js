/**
 * Extract the isosurface f(x,y,z) = level as a triangle soup.
 * @param {(x:number,y:number,z:number)=>number} f scalar field (may return NaN)
 * @param {{xmin:number,xmax:number,ymin:number,ymax:number,zmin:number,zmax:number,
 *          nx:number,ny:number,nz:number,level?:number}} opts
 * @returns {{positions: Float32Array, normals: Float32Array}}
 */
export function marchingCubes(f, opts) {
  const xmin = opts.xmin, xmax = opts.xmax;
  const ymin = opts.ymin, ymax = opts.ymax;
  const zmin = opts.zmin, zmax = opts.zmax;
  const nx = opts.nx | 0, ny = opts.ny | 0, nz = opts.nz | 0;
  const level = opts.level === undefined ? 0 : +opts.level;
  if (!(nx > 0 && ny > 0 && nz > 0)) throw new Error('marchingCubes: nx, ny, nz must be positive integers');

  const sx = nx + 1, sy = ny + 1, sz = nz + 1;
  const dx = (xmax - xmin) / nx;
  const dy = (ymax - ymin) / ny;
  const dz = (zmax - zmin) / nz;
  const hx = dx * 0.5, hy = dy * 0.5, hz = dz * 0.5; // central-difference steps

  // Precomputed axis coordinates (shared by all cells -> exact shared vertices).
  const xs = new Float64Array(sx);
  const ys = new Float64Array(sy);
  const zs = new Float64Array(sz);
  for (let i = 0; i < sx; i++) xs[i] = xmin + i * dx;
  for (let j = 0; j < sy; j++) ys[j] = ymin + j * dy;
  for (let k = 0; k < sz; k++) zs[k] = zmin + k * dz;

  // Sample the field once on the full grid.
  const grid = new Float64Array(sx * sy * sz);
  {
    let p = 0;
    for (let k = 0; k < sz; k++) {
      const z = zs[k];
      for (let j = 0; j < sy; j++) {
        const y = ys[j];
        for (let i = 0; i < sx; i++) grid[p++] = +f(xs[i], y, z);
      }
    }
  }
  const SJ = sx;        // +1 in j
  const SK = sx * sy;   // +1 in k

  // Growable output buffers (floats), doubled on demand.
  let cap = 9 * 512;
  let pos = new Float32Array(cap);
  let nrm = new Float32Array(cap);
  let len = 0;
  function grow(need) {
    let c = cap;
    while (c < need) c *= 2;
    const p2 = new Float32Array(c); p2.set(pos); pos = p2;
    const n2 = new Float32Array(c); n2.set(nrm); nrm = n2;
    cap = c;
  }

  // Per-cell scratch (no per-cell allocation).
  const cv = new Float64Array(8);   // corner values
  const ex = new Float64Array(12);  // edge-vertex coords
  const ey = new Float64Array(12);
  const ez = new Float64Array(12);

  for (let k = 0; k < nz; k++) {
    for (let j = 0; j < ny; j++) {
      let base = k * SK + j * SJ;
      for (let i = 0; i < nx; i++, base++) {
        const v0 = grid[base];
        const v1 = grid[base + 1];
        const v3 = grid[base + SJ];
        const v2 = grid[base + SJ + 1];
        const v4 = grid[base + SK];
        const v5 = grid[base + SK + 1];
        const v7 = grid[base + SK + SJ];
        const v6 = grid[base + SK + SJ + 1];

        // Skip cells with any NaN corner. (NaN !== NaN)
        if (v0 !== v0 || v1 !== v1 || v2 !== v2 || v3 !== v3 ||
            v4 !== v4 || v5 !== v5 || v6 !== v6 || v7 !== v7) continue;

        let ci = 0;
        if (v0 < level) ci |= 1;
        if (v1 < level) ci |= 2;
        if (v2 < level) ci |= 4;
        if (v3 < level) ci |= 8;
        if (v4 < level) ci |= 16;
        if (v5 < level) ci |= 32;
        if (v6 < level) ci |= 64;
        if (v7 < level) ci |= 128;
        if (ci === 0 || ci === 255) continue;

        const edges = EDGE_TABLE[ci];
        cv[0] = v0; cv[1] = v1; cv[2] = v2; cv[3] = v3;
        cv[4] = v4; cv[5] = v5; cv[6] = v6; cv[7] = v7;

        // Interpolate crossed edges.
        for (let e = 0; e < 12; e++) {
          if (!(edges & (1 << e))) continue;
          const a = EDGE_A[e], b = EDGE_B[e];
          const va = cv[a], vb = cv[b];
          const d = vb - va;
          let t = d === 0 ? 0.5 : (level - va) / d;
          if (t < 0) t = 0; else if (t > 1) t = 1;
          const ax = xs[i + CORNER_DX[a]], ay = ys[j + CORNER_DY[a]], az = zs[k + CORNER_DZ[a]];
          ex[e] = ax + t * (xs[i + CORNER_DX[b]] - ax);
          ey[e] = ay + t * (ys[j + CORNER_DY[b]] - ay);
          ez[e] = az + t * (zs[k + CORNER_DZ[b]] - az);
        }

        // Emit triangles. TRI_TABLE winding orients (right-hand-rule) face normals toward
        // the f < level side; the contract wants CCW seen from the grad-f (f > level) side,
        // so emit each triangle with its 2nd and 3rd vertices swapped.
        for (let m = ci << 4; TRI_TABLE[m] !== -1; m += 3) {
          const e0 = TRI_TABLE[m], e1 = TRI_TABLE[m + 2], e2 = TRI_TABLE[m + 1];
          if (len + 9 > cap) grow(len + 9);

          const x0 = ex[e0], y0 = ey[e0], z0 = ez[e0];
          const x1 = ex[e1], y1 = ey[e1], z1 = ez[e1];
          const x2 = ex[e2], y2 = ey[e2], z2 = ez[e2];

          // Geometric face normal (fallback when the field gradient is unusable).
          let fnx = (y1 - y0) * (z2 - z0) - (z1 - z0) * (y2 - y0);
          let fny = (z1 - z0) * (x2 - x0) - (x1 - x0) * (z2 - z0);
          let fnz = (x1 - x0) * (y2 - y0) - (y1 - y0) * (x2 - x0);
          const fl = Math.sqrt(fnx * fnx + fny * fny + fnz * fnz);
          if (fl > 0 && fl === fl) { fnx /= fl; fny /= fl; fnz /= fl; }
          else { fnx = 0; fny = 0; fnz = 1; }

          pos[len] = x0; pos[len + 1] = y0; pos[len + 2] = z0;
          pos[len + 3] = x1; pos[len + 4] = y1; pos[len + 5] = z1;
          pos[len + 6] = x2; pos[len + 7] = y2; pos[len + 8] = z2;

          for (let q = 0; q < 3; q++) {
            const o = len + 3 * q;
            const px = pos[o], py = pos[o + 1], pz = pos[o + 2];
            // n = normalize(grad f), central differences, h = half cell size per axis.
            let gx = (+f(px + hx, py, pz) - +f(px - hx, py, pz)) / (2 * hx);
            let gy = (+f(px, py + hy, pz) - +f(px, py - hy, pz)) / (2 * hy);
            let gz = (+f(px, py, pz + hz) - +f(px, py, pz - hz)) / (2 * hz);
            const gl = Math.sqrt(gx * gx + gy * gy + gz * gz);
            if (gl > 0 && gl < Infinity && gl === gl) {
              nrm[o] = gx / gl; nrm[o + 1] = gy / gl; nrm[o + 2] = gz / gl;
            } else {
              nrm[o] = fnx; nrm[o + 1] = fny; nrm[o + 2] = fnz;
            }
          }
          len += 9;
        }
      }
    }
  }

  return { positions: pos.slice(0, len), normals: nrm.slice(0, len) };
}
